/// Screen breakpoints for JustUI responsive layouts.
///
/// Standardized widths used for media query layout transitions and responsive folding.
abstract final class JustBreakpoints {
  /// Small screen breakpoint (640.0px) - typically mobile landscape / small tablets
  static const double sm = 640.0;

  /// Medium screen breakpoint (768.0px) - typically tablets / portrait iPads
  static const double md = 768.0;

  /// Large screen breakpoint (1024.0px) - typically landscape tablets / desktop monitors
  static const double lg = 1024.0;

  /// Extra large screen breakpoint (1280.0px) - typically standard desktop monitors
  static const double xl = 1280.0;

  /// Double extra large screen breakpoint (1536.0px) - typically large/hi-res screens
  static const double xxl = 1536.0;
}

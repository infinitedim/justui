/// Visual variants for [JustTabs].
enum JustTabVariant {
  /// Thin border indicator at the bottom (or side for vertical tab layouts)
  line,

  /// Card-like outline container surrounding the active tab
  enclosed,

  /// Rounded solid background pill under the active tab
  pill,

  /// Vertical tab navigation bar layout
  vertical,
}
